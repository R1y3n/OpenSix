import { execFile } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, realpathSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { delimiter, extname, isAbsolute, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { randomBytes } from 'node:crypto';
import { promisify } from 'node:util';

const execute = promisify(execFile);
const root = fileURLToPath(new URL('.', import.meta.url));
const outputs = new Map();
const formats = new Map([
  ['.glb','model/gltf-binary'],['.png','image/png'],['.opus','audio/ogg'],
  ['.wav','audio/wav'],['.xma','application/octet-stream'],['.json','application/json'],['.dds','image/vnd-ms.dds'],
  ['.csv','text/csv'],['.xml','application/xml'],['.obj','text/plain'],
]);

export function resourceKind(extension, bytes) {
  if (['zdr','zft','zdd'].includes(extension)) return 'model';
  if (['zbn','zbd'].includes(extension)) return 'collision';
  if (extension==='ztd') return 'textures';
  if (extension==='zcd') return 'clips';
  if (bytes?.toString('ascii',16,20)==='0DRP') return 'metadata';
  if (bytes?.toString('ascii',0,4)==='PSIN') return 'psin';
  if (['awc','zawc','adat'].includes(extension) || bytes?.toString('ascii',0,4)==='ADAT') return 'bank';
  return null;
}

function aligned(size) { return Math.ceil(size/4)*4; }

function within(folder, path) {
  const rel = relative(folder,path);
  return rel && rel !== '..' && !rel.startsWith('..'+sep) && !isAbsolute(rel);
}

function embedModelImages(folder) {
  const path = join(folder,'model.glb');
  const glb = readFileSync(path);
  const end = 20 + glb.readUInt32LE(12);
  if (glb.toString('ascii',0,4)!=='glTF' || end+8>glb.length) throw new Error('Invalid model generated by the decoder.');
  const content = JSON.parse(glb.toString('utf8',20,end).trimEnd());
  const data = [glb.subarray(end+8,end+8+glb.readUInt32LE(end))];
  let size = data[0].length;
  for (const image of content.images ?? []) {
    if (!image.uri) continue;
    const target = resolve(folder,decodeURIComponent(image.uri));
    if (!within(folder,target)) throw new Error('Model texture path exceeds the preview directory.');
    const png = readFileSync(target);
    const padded = aligned(png.length);
    image.bufferView = content.bufferViews.push({buffer:0,byteOffset:size,byteLength:png.length})-1;
    image.mimeType = 'image/png';
    delete image.uri;
    data.push(png,Buffer.alloc(padded-png.length));
    size += padded;
  }
  content.buffers[0].byteLength = size;
  const json = Buffer.from(JSON.stringify(content));
  const header = Buffer.alloc(20);
  header.write('glTF');
  header.writeUInt32LE(2,4);
  header.writeUInt32LE(28+aligned(json.length)+size,8);
  header.writeUInt32LE(aligned(json.length),12);
  header.write('JSON',16);
  const bin = Buffer.alloc(8);
  bin.writeUInt32LE(size);
  bin.write('BIN\0',4);
  writeFileSync(path,Buffer.concat([header,json,Buffer.alloc(aligned(json.length)-json.length,32),bin,...data]));
}

export async function buildAssetPreview(request, bytes, clip, parts=[]) {
  const isPool=request.kind.startsWith('pool');
  const name = isPool || ['wardrobe','gpuBvhMesh'].includes(request.kind) ? 'opensix-pool.exe' : 'opensix-preview.exe';
  const worker = process.resourcesPath && existsSync(join(process.resourcesPath,name))
    ? join(process.resourcesPath,name)
    : join(root,'worker',name);
  const folder = mkdtempSync(join(tmpdir(),'opensix-view-'));
  try {
    if (bytes) writeFileSync(join(folder,'entry.bin'),bytes);
    if (clip) writeFileSync(join(folder,'clip.bin'),clip);
    for (const [index,part] of parts.entries()) writeFileSync(join(folder,'part-'+index+'.bin'),part);
    writeFileSync(join(folder,'request.json'),JSON.stringify(request));
    const maxBuffer = request.kind==='poolIndex' ? 64*1024*1024 : 4*1024*1024;
    const {stdout} = await execute(worker,[folder],{windowsHide:true,timeout:120_000,maxBuffer,
      env:isPool ? poolEnvironment() : process.env});
    const result = JSON.parse(stdout.trim().split(/\r?\n/).at(-1));
    if (['poolIndex','gpuBvhMesh','unrecognized'].includes(result.type)) {
      rmSync(folder,{recursive:true,force:true});
      return result;
    }
    if (result.type==='model') embedModelImages(folder);
    if (result.type==='bank' && result.tracks.some(track=>track.file==='track.xma')) {
      await addXmaPlayback(folder,result);
    }
    return keepPreview(folder,result,request.archive ? [request.archive] : []);
  } catch (error) {
    rmSync(folder,{recursive:true,force:true});
    throw new Error(error.stderr?.toString().trim() || error.message);
  }
}

function keepPreview(folder,result,sources=[]) {
  const id = randomBytes(16).toString('hex');
  outputs.set(id,{folder,sources});
  while (outputs.size>5) removePreview(outputs.keys().next().value);
  return {...result,id};
}

export function previewMeshGlb(data, details) {
  const folder = mkdtempSync(join(tmpdir(),'opensix-view-'));
  try {
    writeFileSync(join(folder,'model.glb'),data);
    return keepPreview(folder,{type:'model',file:'model.glb',items:[],lods:[],...details});
  } catch (error) {
    rmSync(folder,{recursive:true,force:true});
    throw error;
  }
}

function poolEnvironment() {
  if (process.env.OPENSIX_BCPACK_TABLES) return process.env;
  const portable=process.env.PORTABLE_EXECUTABLE_DIR;
  const path=[process.resourcesPath && join(process.resourcesPath,'bcpack-tables.bin'),
    portable && isAbsolute(portable) && join(portable,'bcpack-tables.bin'),
    join(root,'..','.deps','victory','crates','victory-formats','src','bcpack-tables.bin')]
    .find(candidate=>candidate && existsSync(candidate));
  return path ? {...process.env,OPENSIX_BCPACK_TABLES:path} : process.env;
}

async function addXmaPlayback(folder, result) {
  const paths = (process.env.PATH ?? '').split(delimiter)
    .filter(path=>isAbsolute(path)).map(path=>join(path,'ffmpeg.exe'));
  const ffmpeg = [process.env.OPENSIX_FFMPEG,...paths].find(path=>path && isAbsolute(path) && existsSync(path));
  if (!ffmpeg) { result.note='Install FFmpeg or set OPENSIX_FFMPEG to play XMA2.'; return; }
  const args = ['-nostdin','-hide_banner','-loglevel','error','-protocol_whitelist','file,pipe','-f','wav',
    '-i',join(folder,'track.xma'),'-map','0:a:0','-vn','-c:a','pcm_s16le','-y',
    '-t','120','-fs','134217728',join(folder,'decoded.wav')];
  try {
    await execute(ffmpeg,args,{windowsHide:true,timeout:45_000,maxBuffer:128*1024});
    if (statSync(join(folder,'decoded.wav')).size < 80) throw new Error('Empty PCM output');
    result.tracks.push({name:'XMA2 decoded preview',file:'decoded.wav',playable:true});
  } catch {
    result.note='FFmpeg could not decode this XMA2 stream.';
  }
}

function removePreview(id) {
  const folder = outputs.get(id)?.folder;
  outputs.delete(id);
  if (folder) rmSync(folder,{recursive:true,force:true});
}

export function clearAssetPreviews() {
  for (const id of outputs.keys()) removePreview(id);
}

export function assetPreviewFile(id, name) {
  const output = outputs.get(id);
  const folder = output?.folder;
  const mime = (typeof name==='string' && /^[\w.-]+$/.test(name)) ? formats.get(extname(name)) : undefined;
  if (!folder || !mime) return null;
  const path = join(folder,name);
  if (!existsSync(path)) return null;
  const absolute = realpathSync(path);
  if (!within(realpathSync(folder),absolute) || !statSync(absolute).isFile()) return null;
  return {path:absolute,mime,sources:output.sources};
}
